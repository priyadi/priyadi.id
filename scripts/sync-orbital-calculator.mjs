#!/usr/bin/env node
/**
 * Copies what the article needs out of the Orbital AI Datacenter Calculator.
 *
 * The calculator is a static page kept in its own repository. The article in
 * src/components/OrbitalDatacenter computes with the calculator's own code
 * and speaks with its own Indonesian wording, so the two cannot drift apart.
 * This script writes two modules there:
 *
 * - model.generated.ts: the model, the input definitions, the presets, the
 *   number formatters and the orbit geometry, verbatim from index.html
 * - land.generated.ts: the outline of the continents drawn on the globe
 * - id.generated.ts: the translator from i18n.js, verbatim, and the part of
 *   the Indonesian dictionary (lang-id.js) the article can use
 *
 * Every piece is located by a marker in the source. If a marker is gone the
 * script stops with an error instead of writing something incomplete.
 *
 * Usage: node scripts/sync-orbital-calculator.mjs [path/to/orbital-ai-datacenter]
 */
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const siteDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.resolve(
  process.argv[2] ?? path.join(siteDir, '..', 'orbital-ai-datacenter'),
);
const targetDir = path.join(siteDir, 'src/components/OrbitalDatacenter');

/** Runs git in the calculator's repository; undefined if that fails. */
function git(args) {
  try {
    return execFileSync('git', ['-C', sourceDir, ...args], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch {
    return undefined;
  }
}

// Work from the last commit, not from whatever is being edited: the output
// is labelled with a revision and should match it. Without git, fall back to
// the files on disk.
const revision = git(['rev-parse', '--short', 'HEAD'])?.trim();
const files = ['index.html', 'i18n.js', 'lang-id.js'];
const pending = revision ? git(['status', '--porcelain', '--', ...files])?.trim() : '';
const label = revision ?? 'not under version control';

function read(file) {
  const committed = revision && git(['show', `HEAD:${file}`]);
  return committed ?? fs.readFileSync(path.join(sourceDir, file), 'utf8');
}

/** The single match of `pattern` in `text`, or stops the script. */
function only(text, pattern, what) {
  const matches = text.match(pattern) ?? [];
  if (matches.length !== 1) {
    throw new Error(`Expected exactly one ${what}, found ${matches.length}.`);
  }
  return matches[0];
}

/** The part of `text` from one marker up to (not including) the next. */
function between(text, start, end, what) {
  const from = text.indexOf(start);
  const to = from < 0 ? -1 : text.indexOf(end, from + start.length);
  if (from < 0 || to < 0) {
    throw new Error(`Could not find the ${what}.`);
  }
  return text.slice(from, to).trim();
}

const header = (file) => `// @ts-nocheck
// Generated by scripts/sync-orbital-calculator.mjs from
// orbital-ai-datacenter/${file} (${label}). Do not edit by hand.
`;

// --- Model -------------------------------------------------------------------

const page = read('index.html');
const script = between(page, '<script>\n// ---------- constants', '</script>', 'page script').slice(
  '<script>'.length,
);

const modelParts = [
  between(script, '// ---------- constants ----------', '// ---------- references ----------', 'constants'),
  between(script, '// ---------- formatting ----------', '// ---------- render ----------', 'formatters'),
  between(script, 'const CTLS=[', '\nconst state=', 'input definitions'),
  between(script, '// ---------- model ----------', '// ---------- formatting ----------', 'model'),
  between(script, 'const PRESETS=[', '\nfunction applyPreset', 'presets'),
  // Where the Sun, the orbit and the station are, for the orbit view.
  between(script, 'const OMEGA_E=', '\nfunction initGlobe(', 'orbit geometry'),
  // The orbit view's own defaults, which are not model inputs.
  `const ${only(script, /\bINCL_DEF=\d+(?:\.\d+)?/g, 'default inclination')}, ${only(script, /\bSPEED_DEF=\d+(?:\.\d+)?/g, 'default animation speed')};`,
].join('\n\n');

const modelExports = [
  'RE', 'YEAR', 'PITCH', 'ISS_ARRAY', 'ISS_MASS',
  'CTLS', 'PRESETS', 'model',
  'OMEGA_E', 'orbitFrame', 'satPos', 'inShadow', 'INCL_DEF', 'SPEED_DEF',
  'fmtNum', 'fmtSI', 'fmtArea', 'fmtMass', 'fmtTime', 'fmtMoney', 'fmtUSD', 'fmtEnergy',
];
for (const name of modelExports) {
  if (!new RegExp(`(?:\\b${name}\\s*=[^=]|function\\s+${name}\\s*\\()`).test(modelParts)) {
    throw new Error(`The model module would not define ${name}.`);
  }
}
if (/\b(document|window|location|history|navigator|I18N)\b\s*[.[(]/.test(modelParts)) {
  throw new Error('The model code touches the page; it must stay a pure computation.');
}

const modelFile = path.join(targetDir, 'model.generated.ts');
fs.writeFileSync(
  modelFile,
  `${header('index.html')}//
// The calculator's model, inputs, presets and formatters, verbatim. Use them
// through ./model.ts, which adds types.

${modelParts}

export {${modelExports.join(', ')}};
`,
);

// --- Land outline ------------------------------------------------------------

const land = between(script, 'const LAND_TOPO=', '\nconst OV=', 'land outline').replace(/;\s*$/, '');
const topology = JSON.parse(land.slice('const LAND_TOPO='.length));
if (topology.type !== 'Topology' || !topology.objects?.land) {
  throw new Error('The land outline is not the TopoJSON it used to be.');
}
fs.writeFileSync(
  path.join(targetDir, 'land.generated.ts'),
  `${header('index.html')}//
// The continents, as TopoJSON, for the globe in the orbit view. Loaded on
// demand: it is 55 kB.

export const land = ${JSON.stringify(topology)};
`,
);

// --- Indonesian --------------------------------------------------------------

// The translator: the pure part of i18n.js, between its number handling and
// its DOM handling. It expects `dict`, `D` and `missing` around it.
const translator = between(read('i18n.js'), '// ---- numbers', '// ---- DOM', 'translator in i18n.js');
if (/\b(document|window|location|localStorage)\b/.test(translator)) {
  throw new Error('The translator touches the page; it must stay pure.');
}

const dictionarySource = read('lang-id.js');
const whole = new Function(`const window = {}; ${dictionarySource}; return window.I18N_ID;`)();
if (!whole || typeof whole !== 'object') {
  throw new Error('lang-id.js did not define I18N_ID.');
}

// The whole dictionary is 150 kB, most of it long explanations the article
// does not show. Keep the texts the article can ask for: everything attached
// to an input or a preset, and every short entry (units, labels, templates).
const SHORT = 64;
const {CTLS, PRESETS} = await import(`${pathToFileURL(modelFile).href}?${Date.now()}`);
const wanted = new Set([
  ...CTLS.flatMap((control) => [control.g, control.label, control.note]),
  ...PRESETS.flatMap((preset) => [preset.n, preset.d]),
]);
const dictionary = Object.fromEntries(
  Object.entries(whole).filter(([key]) => key.length <= SHORT || wanted.has(key)),
);

fs.writeFileSync(
  path.join(targetDir, 'id.generated.ts'),
  `${header('i18n.js and lang-id.js')}//
// The calculator's English-to-Indonesian translator and the part of its
// dictionary the article uses. Use them through ./id.ts.

export const dictionary = ${JSON.stringify(dictionary, null, 1)};

/** Returns the calculator's tr(): English text in, Indonesian text out. */
export function createTranslator(entries) {
  const dict = Object.assign(Object.create(null), entries);
  const D = () => dict;
  const missing = new Set();

  ${translator}

  return tr;
}
`,
);

if (pending) {
  console.warn(
    'Note: the calculator has uncommitted changes, which are not included:\n' + pending,
  );
}
console.log(
  `Calculator ${label}: model ${modelParts.length} B; ` +
    `${Object.keys(dictionary).length} of ${Object.keys(whole).length} dictionary entries.`,
);
