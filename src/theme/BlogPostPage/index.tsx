import React, {type ReactNode} from 'react';
import clsx from 'clsx';
import Link from '@docusaurus/Link';
import {
  HtmlClassNameProvider,
  ThemeClassNames,
  useThemeConfig,
} from '@docusaurus/theme-common';
import {
  BlogPostProvider,
  useBlogPost,
} from '@docusaurus/plugin-content-blog/client';
import {blogPostContainerID} from '@docusaurus/utils-common';
import Layout from '@theme/Layout';
import MDXContent from '@theme/MDXContent';
import BlogPostPageMetadata from '@theme/BlogPostPage/Metadata';
import BlogPostPageStructuredData from '@theme/BlogPostPage/StructuredData';
import ContentVisibility from '@theme/ContentVisibility';
import EditThisPage from '@theme/EditThisPage';
import TagsListInline from '@theme/TagsListInline';
import type {Props} from '@theme/BlogPostPage';
import Comments from '@site/src/components/Comments';
import {usePostDate} from '@site/src/components/Story';
import styles from './styles.module.css';

// A table of contents is offered once a post has this many headings.
const TOC_MIN_HEADINGS = 3;

function Byline(): ReactNode {
  const {metadata, assets} = useBlogPost();
  const formatDate = usePostDate();
  const {authors, date, readingTime} = metadata;
  const avatar = assets.authorsImageUrls[0] ?? authors[0]?.imageURL;

  return (
    <div className={styles.byline}>
      {avatar && (
        <img className={styles.avatar} src={avatar} alt="" width={44} height={44} />
      )}
      <div>
        {authors.length > 0 && (
          <p className={styles.authors}>
            Oleh{' '}
            {authors.map((author, index) => {
              const href = author.page?.permalink ?? author.url;
              return (
                <React.Fragment key={author.key ?? author.name}>
                  {index > 0 && ', '}
                  {href ? <Link to={href}>{author.name}</Link> : author.name}
                </React.Fragment>
              );
            })}
          </p>
        )}
        <p className={styles.dateline}>
          <time dateTime={date}>{formatDate(date)}</time>
          {readingTime !== undefined && (
            <span>{Math.max(1, Math.round(readingTime))} menit baca</span>
          )}
        </p>
      </div>
    </div>
  );
}

function TableOfContents(): ReactNode {
  const {toc, frontMatter} = useBlogPost();
  const {tableOfContents} = useThemeConfig();
  const minLevel =
    frontMatter.toc_min_heading_level ?? tableOfContents.minHeadingLevel;
  const maxLevel =
    frontMatter.toc_max_heading_level ?? tableOfContents.maxHeadingLevel;
  const headings = toc.filter(
    ({level}) => level >= minLevel && level <= maxLevel,
  );

  if (
    frontMatter.hide_table_of_contents ||
    headings.length < TOC_MIN_HEADINGS
  ) {
    return null;
  }

  // The stock TOC component measures the stock navbar, which this site
  // replaces, so the list is rendered here.
  return (
    <details className={styles.toc}>
      <summary>Daftar isi</summary>
      <ul>
        {headings.map(({id, level, value}) => (
          <li key={id} style={{paddingLeft: `${(level - minLevel) * 1.25}rem`}}>
            {/* Heading HTML is generated by Docusaurus from the post. */}
            <a href={`#${id}`} dangerouslySetInnerHTML={{__html: value}} />
          </li>
        ))}
      </ul>
    </details>
  );
}

function AdjacentPosts(): ReactNode {
  const {metadata} = useBlogPost();
  // Docusaurus names these by position in the list: "prev" is the newer post.
  const {prevItem: newer, nextItem: older} = metadata;

  if (!newer && !older) {
    return null;
  }

  return (
    <nav className={styles.adjacent} aria-label="Tulisan lain">
      {older && (
        <Link to={older.permalink} className={styles.older}>
          <span>Tulisan sebelumnya</span>
          {older.title}
        </Link>
      )}
      {newer && (
        <Link to={newer.permalink} className={styles.newer}>
          <span>Tulisan berikutnya</span>
          {newer.title}
        </Link>
      )}
    </nav>
  );
}

function Article({children}: {children: ReactNode}): ReactNode {
  const {metadata, frontMatter} = useBlogPost();
  const {title, tags, editUrl} = metadata;
  const {description} = frontMatter;
  const {comments = true} = frontMatter as {comments?: boolean};

  return (
    <Layout>
      <main className={styles.page}>
        <div className="columns">
          <ContentVisibility metadata={metadata} />
        </div>
        <article>
          <header className={clsx('columns', styles.header)}>
            <h1 className={styles.headline}>{title}</h1>
            {description && <p className={styles.dek}>{description}</p>}
            <Byline />
            <TableOfContents />
          </header>
          {/* The id is how the feed generator finds the post body. */}
          <div
            id={blogPostContainerID}
            className={clsx('columns', 'markdown', 'prose')}>
            <MDXContent>{children}</MDXContent>
          </div>
          {(tags.length > 0 || editUrl) && (
            <footer className={clsx('columns', styles.footer)}>
              {tags.length > 0 && <TagsListInline tags={tags} />}
              {editUrl && (
                <div>
                  <EditThisPage editUrl={editUrl} />
                </div>
              )}
            </footer>
          )}
        </article>
        <div className={clsx('columns', styles.after)}>
          <AdjacentPosts />
          {comments && <Comments />}
        </div>
      </main>
    </Layout>
  );
}

export default function BlogPostPage(props: Props): ReactNode {
  const BlogPostContent = props.content;

  return (
    <BlogPostProvider content={props.content} isBlogPostPage>
      <HtmlClassNameProvider
        className={clsx(
          ThemeClassNames.wrapper.blogPages,
          ThemeClassNames.page.blogPostPage,
        )}>
        <BlogPostPageMetadata />
        <BlogPostPageStructuredData />
        <Article>
          <BlogPostContent />
        </Article>
      </HtmlClassNameProvider>
    </BlogPostProvider>
  );
}
