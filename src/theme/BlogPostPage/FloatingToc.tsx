import React, {
  type ReactNode,
  type RefObject,
  useEffect,
  useId,
  useRef,
  useState,
} from 'react';
import clsx from 'clsx';
import type {TOCItem} from '@docusaurus/mdx-loader';
import styles from './FloatingToc.module.css';

/**
 * Where the reader is: whether the post body is on screen past the header,
 * and which heading was passed last. Measured on scroll, once a frame.
 */
function usePosition(
  headings: readonly TOCItem[],
  start: RefObject<HTMLElement | null>,
): {shown: boolean; active: string | undefined} {
  const [shown, setShown] = useState(false);
  const [active, setActive] = useState<string>();

  useEffect(() => {
    const article = start.current?.closest('article');
    if (!start.current || !article) {
      return undefined;
    }

    let frame = 0;
    const measure = () => {
      frame = 0;
      const height = window.innerHeight;
      // Headings scrolled to stop below anything pinned at the top.
      const pinned =
        parseFloat(document.documentElement.style.scrollPaddingTop) || 0;
      const line = pinned + height * 0.2;

      let current: string | undefined;
      for (const {id} of headings) {
        const heading = document.getElementById(id);
        if (heading && heading.getBoundingClientRect().top <= line) {
          current = id;
        } else if (heading) {
          break;
        }
      }
      setActive(current);
      setShown(
        start.current!.getBoundingClientRect().bottom < 0 &&
          article.getBoundingClientRect().bottom > height * 0.6,
      );
    };
    const schedule = () => {
      frame ||= window.requestAnimationFrame(measure);
    };

    measure();
    window.addEventListener('scroll', schedule, {passive: true});
    window.addEventListener('resize', schedule);
    return () => {
      window.cancelAnimationFrame(frame);
      window.removeEventListener('scroll', schedule);
      window.removeEventListener('resize', schedule);
    };
  }, [headings, start]);

  return {shown, active};
}

/**
 * The table of contents, kept in view while the post is read, once the one
 * in the header has scrolled away. Where the margin has room it is the whole
 * list, beside the text; elsewhere a button in the lower corner that names
 * the section being read and opens the list. The top of the window is left
 * to the bars some articles pin there.
 */
export default function FloatingToc({
  headings,
  minLevel,
  start,
}: {
  headings: readonly TOCItem[];
  minLevel: number;
  /** The end of the header: the list shows once this has scrolled past. */
  start: RefObject<HTMLElement | null>;
}): ReactNode {
  const {shown, active} = usePosition(headings, start);
  const [open, setOpen] = useState(false);
  const nav = useRef<HTMLElement>(null);
  const button = useRef<HTMLButtonElement>(null);
  const listId = useId();
  const current = headings.find(({id}) => id === active);

  // Closes on Escape, on a click elsewhere, and when the list goes away.
  useEffect(() => {
    if (!open) {
      return undefined;
    }
    const onKey = (event: KeyboardEvent) => {
      if (event.key === 'Escape') {
        setOpen(false);
        button.current?.focus();
      }
    };
    const onClick = (event: MouseEvent) => {
      if (!nav.current?.contains(event.target as Node)) {
        setOpen(false);
      }
    };
    document.addEventListener('keydown', onKey);
    document.addEventListener('click', onClick);
    return () => {
      document.removeEventListener('keydown', onKey);
      document.removeEventListener('click', onClick);
    };
  }, [open]);

  useEffect(() => {
    if (!shown) {
      setOpen(false);
    }
  }, [shown]);

  return (
    <nav
      ref={nav}
      className={clsx(styles.toc, shown && styles.shown, open && styles.open)}
      aria-label="Daftar isi"
      // Out of the tab order while it is out of sight.
      inert={!shown || undefined}>
      <p className={styles.title} aria-hidden="true">
        Daftar isi
      </p>
      <ul id={listId} className={styles.list}>
        {headings.map(({id, level, value}) => (
          <li
            key={id}
            style={{paddingLeft: `${(level - minLevel) * 0.85}rem`}}>
            <a
              href={`#${id}`}
              aria-current={id === active ? 'location' : undefined}
              onClick={() => setOpen(false)}
              // Heading HTML is generated by Docusaurus from the post.
              dangerouslySetInnerHTML={{__html: value}}
            />
          </li>
        ))}
      </ul>
      <button
        ref={button}
        type="button"
        className={styles.button}
        aria-expanded={open}
        aria-controls={listId}
        onClick={() => setOpen((o) => !o)}>
        <svg
          className={styles.icon}
          viewBox="0 0 16 16"
          fill="none"
          stroke="currentColor"
          strokeWidth="1.5"
          strokeLinecap="round"
          aria-hidden="true">
          <path d="M2.5 4h11M2.5 8h11M2.5 12h7" />
        </svg>
        <span className={styles.buttonLabel}>Daftar isi</span>
        {current && (
          <span
            className={styles.buttonCurrent}
            // Heading HTML is generated by Docusaurus from the post.
            dangerouslySetInnerHTML={{__html: current.value}}
          />
        )}
      </button>
    </nav>
  );
}
